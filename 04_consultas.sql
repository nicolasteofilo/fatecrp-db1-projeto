-- Q1 (SELECT simples): produtos abaixo do estoque minimo
SELECT NOME, ESTOQUE_ATUAL, ESTOQUE_MINIMO
FROM   PRODUTO
WHERE  ESTOQUE_ATUAL < ESTOQUE_MINIMO;

-- Q2 (JOIN): produtos com o nome da categoria
SELECT P.NOME AS PRODUTO, C.NOME AS CATEGORIA, P.ESTOQUE_ATUAL
FROM   PRODUTO P
       INNER JOIN CATEGORIA C ON C.ID_CATEGORIA = P.ID_CATEGORIA;

-- Q3 (agregacao): total de produtos e estoque total
SELECT COUNT(*) AS QTD_PRODUTOS, SUM(ESTOQUE_ATUAL) AS ESTOQUE_TOTAL
FROM   PRODUTO;

-- Q4 (GROUP BY): quantidade de produtos por categoria
SELECT C.NOME AS CATEGORIA, COUNT(*) AS QTD_PRODUTOS
FROM   PRODUTO P
       INNER JOIN CATEGORIA C ON C.ID_CATEGORIA = P.ID_CATEGORIA
GROUP BY C.NOME;

-- Q5 (JOIN + GROUP BY + SUM): gasto total com cada fornecedor
SELECT F.RAZAO_SOCIAL, SUM(M.QUANTIDADE * M.PRECO_UNITARIO) AS GASTO_TOTAL
FROM   MOVIMENTACAO M
       INNER JOIN FORNECEDOR F ON F.ID_FORNECEDOR = M.ID_FORNECEDOR
WHERE  M.TIPO = 'ENTRADA'
GROUP BY F.RAZAO_SOCIAL;

-- Q6 (HAVING): fornecedores com gasto acima de R$ 1.000
SELECT F.RAZAO_SOCIAL, SUM(M.QUANTIDADE * M.PRECO_UNITARIO) AS GASTO_TOTAL
FROM   MOVIMENTACAO M
       INNER JOIN FORNECEDOR F ON F.ID_FORNECEDOR = M.ID_FORNECEDOR
WHERE  M.TIPO = 'ENTRADA'
GROUP BY F.RAZAO_SOCIAL
HAVING SUM(M.QUANTIDADE * M.PRECO_UNITARIO) > 1000;

-- Q7 (subconsulta): produtos que nunca tiveram saida
SELECT NOME, ESTOQUE_ATUAL
FROM   PRODUTO
WHERE  ID_PRODUTO NOT IN (SELECT ID_PRODUTO
                          FROM   MOVIMENTACAO
                          WHERE  TIPO = 'SAIDA');

-- Q8 (UNION): produtos que precisam de atencao
SELECT NOME, 'Abaixo do minimo' AS MOTIVO
FROM   PRODUTO
WHERE  ESTOQUE_ATUAL < ESTOQUE_MINIMO
UNION
SELECT NOME, 'Sem saidas' AS MOTIVO
FROM   PRODUTO
WHERE  ID_PRODUTO NOT IN (SELECT ID_PRODUTO
                          FROM   MOVIMENTACAO
                          WHERE  TIPO = 'SAIDA');
