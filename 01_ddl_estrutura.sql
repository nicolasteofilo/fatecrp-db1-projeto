-- 01_ddl_estrutura.sql
DROP TABLE MOVIMENTACAO;
DROP TABLE PRODUTO;
DROP TABLE FORNECEDOR;
DROP TABLE CATEGORIA;

CREATE TABLE CATEGORIA (
  ID_CATEGORIA NUMBER GENERATED ALWAYS AS IDENTITY,
  NOME         VARCHAR2(60) NOT NULL,
  CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA),
  CONSTRAINT UK_CATEGORIA_NOME UNIQUE (NOME)
);

CREATE TABLE FORNECEDOR (
  ID_FORNECEDOR NUMBER GENERATED ALWAYS AS IDENTITY,
  RAZAO_SOCIAL  VARCHAR2(120) NOT NULL,
  CNPJ          VARCHAR2(14) NOT NULL,
  CONSTRAINT PK_FORNECEDOR PRIMARY KEY (ID_FORNECEDOR),
  CONSTRAINT UK_FORNECEDOR_CNPJ UNIQUE (CNPJ)
);

CREATE TABLE PRODUTO (
  ID_PRODUTO     NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_CATEGORIA   NUMBER NOT NULL,
  NOME           VARCHAR2(100) NOT NULL,
  ESTOQUE_ATUAL  NUMBER(10,2) DEFAULT 0 NOT NULL,
  ESTOQUE_MINIMO NUMBER(10,2) DEFAULT 0 NOT NULL,
  CONSTRAINT PK_PRODUTO PRIMARY KEY (ID_PRODUTO),
  CONSTRAINT FK_PRODUTO_CATEGORIA FOREIGN KEY (ID_CATEGORIA) REFERENCES CATEGORIA (ID_CATEGORIA),
  CONSTRAINT CK_PRODUTO_ESTOQUE CHECK (ESTOQUE_ATUAL >= 0)
);

CREATE TABLE MOVIMENTACAO (
  ID_MOVIMENTACAO NUMBER GENERATED ALWAYS AS IDENTITY,
  ID_PRODUTO      NUMBER NOT NULL,
  ID_FORNECEDOR   NUMBER,
  TIPO            VARCHAR2(10) NOT NULL,
  QUANTIDADE      NUMBER(10,2) NOT NULL,
  DATA_HORA       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  PRECO_UNITARIO  NUMBER(10,2),
  CONSTRAINT PK_MOVIMENTACAO PRIMARY KEY (ID_MOVIMENTACAO),
  CONSTRAINT FK_MOV_PRODUTO FOREIGN KEY (ID_PRODUTO) REFERENCES PRODUTO (ID_PRODUTO),
  CONSTRAINT FK_MOV_FORNECEDOR FOREIGN KEY (ID_FORNECEDOR) REFERENCES FORNECEDOR (ID_FORNECEDOR),
  CONSTRAINT CK_MOV_TIPO CHECK (TIPO IN ('ENTRADA', 'SAIDA')),
  CONSTRAINT CK_MOV_QUANTIDADE CHECK (QUANTIDADE > 0),
  CONSTRAINT CK_MOV_PRECO CHECK (PRECO_UNITARIO > 0),
  CONSTRAINT CK_MOV_FORNEC_PRECO CHECK (TIPO = 'ENTRADA' OR (ID_FORNECEDOR IS NULL AND PRECO_UNITARIO IS NULL))
);

ALTER TABLE FORNECEDOR
  ADD CONSTRAINT CK_FORNECEDOR_CNPJ CHECK (LENGTH(CNPJ) = 14);
